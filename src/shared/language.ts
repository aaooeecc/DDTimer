export type Message = keyof typeof english
type Values = Record<string, string | number>

export function translator(language: Language) {
  return (message: Message, values?: Values): string => {
    const template = language === 'en' ? english[message] : message
    return values ? template.replace(/\{(\w+)\}/g, (placeholder, key) => String(values[key] ?? placeholder)) : template
  }
}
